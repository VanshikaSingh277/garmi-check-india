"""Write apps/api/requirements.lock: every package the container installs (direct and indirect), pinned with its
sha256, for the image's platform (Linux x86_64, CPython 3.11). The Dockerfile installs it with --require-hashes
(spec §8.10). Re-run after changing requirements.txt:   python scripts/lock_requirements.py
"""
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
REQ = os.path.join(ROOT, "apps", "api", "requirements.txt")
LOCK = os.path.join(ROOT, "apps", "api", "requirements.lock")
PLATFORM = ["--platform", "manylinux_2_28_x86_64", "--platform", "manylinux_2_17_x86_64", "--platform", "manylinux2014_x86_64",
            "--python-version", "3.11", "--implementation", "cp", "--only-binary=:all:"]

with tempfile.TemporaryDirectory() as tmp:
    report = os.path.join(tmp, "report.json")
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "--dry-run", "--ignore-installed", "--target", os.path.join(tmp, "t"),
                    "--report", report, *PLATFORM, "-r", REQ], check=True)
    data = json.load(open(report, encoding="utf-8"))

lines = ["# Generated by scripts/lock_requirements.py from requirements.txt (Linux x86_64, CPython 3.11). Do not edit by hand.", ""]
for item in sorted(data["install"], key=lambda x: x["metadata"]["name"].lower()):
    name, version = item["metadata"]["name"], item["metadata"]["version"]
    sha = item["download_info"]["archive_info"]["hashes"]["sha256"]
    lines.append(f"{name}=={version} \\\n    --hash=sha256:{sha}")
with open(LOCK, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{len(data['install'])} packages -> {os.path.relpath(LOCK, ROOT)}")
